"""Regenerate the cards block of README.md from cards/*.json.

Only the text between the two markers is replaced, so the rest of the README
stays hand-written. Alt text is built from the same card fields the SVGs use,
which keeps screen-reader text and the images in sync.
"""
from __future__ import annotations

from html import escape

START = "<!-- cards:start (generated by pipeline/render_readme.py; edit cards/*.json) -->"
END = "<!-- cards:end -->"


def _alt(card: dict) -> str:
    return escape(f"{card['title']}: {' '.join(card['summary'])} Result: {card['headline']}. "
                  f"Doesn't show: {' '.join(card['limitation'])}", quote=True)


def _card(card: dict, slug: str) -> str:
    return (f'  <a href="{escape(card["links"]["repo"], quote=True)}">\n'
            f"    <picture>\n"
            f'      <source media="(prefers-color-scheme: dark)" srcset="assets/card-{slug}-dark.svg">\n'
            f'      <source media="(prefers-color-scheme: light)" srcset="assets/card-{slug}-light.svg">\n'
            f'      <img alt="{_alt(card)}" src="assets/card-{slug}-dark.svg" width="49%">\n'
            f"    </picture>\n"
            f"  </a>")


def block(cards: list[dict], slugs: list[str]) -> str:
    rows = []
    for i in range(0, len(cards), 2):
        pair = [_card(c, s) for c, s in zip(cards[i:i + 2], slugs[i:i + 2])]
        rows.append("<p>\n" + "\n".join(pair) + "\n</p>")
    demos = " · ".join(f"[{c['title']}]({c['links']['demo']})" for c in cards if c["links"].get("demo"))
    return f"{START}\n" + "\n".join(rows) + f"\n\n<sub>Live demos: {demos}</sub>\n{END}"


def update(readme: str, cards: list[dict], slugs: list[str]) -> str:
    """Return ``readme`` with the cards block replaced. Raises if markers are missing."""
    start, end = readme.find(START), readme.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError("README is missing the cards:start / cards:end markers")
    return readme[:start] + block(cards, slugs) + readme[end + len(END):]
